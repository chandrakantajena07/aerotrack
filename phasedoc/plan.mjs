#!/usr/bin/env node
// phasedoc plan script — JSON-backed task database + mirror generator.
// Verbs: init, tick <id>, part <id>, note <id> <text...>, add <id> <parent> <title> <acceptance> <component>, tree, components, mirror
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const DIR = dirname(fileURLToPath(import.meta.url))
const DB_PATH = join(DIR, 'tasks.json')
const MIRROR_PATH = join(DIR, 'BUILDPLAN.md')

function loadDb() {
  if (!existsSync(DB_PATH)) {
    console.error('No tasks.json yet — run `node plan.mjs init` first.')
    process.exit(1)
  }
  return JSON.parse(readFileSync(DB_PATH, 'utf8'))
}

function saveDb(tasks) {
  writeFileSync(DB_PATH, JSON.stringify(tasks, null, 2) + '\n')
}

function nowIso() {
  return new Date().toISOString()
}

async function cmdInit() {
  if (existsSync(DB_PATH)) {
    console.error('tasks.json already exists — refusing to overwrite. Delete it first if you mean to reseed.')
    process.exit(1)
  }
  const { seedTasks } = await import('./seed-tasks.mjs')
  const tasks = seedTasks.map((t) => ({ ...t, status: t.acceptance ? 'open' : 'open', note: '', tickedAt: null }))
  saveDb(tasks)
  console.log(`Seeded ${tasks.length} tasks into ${DB_PATH}`)
  cmdMirror()
}

function findTask(tasks, id) {
  const t = tasks.find((t) => t.id === id)
  if (!t) {
    console.error(`No such task id: ${id}`)
    process.exit(1)
  }
  return t
}

function cmdTick(id) {
  const tasks = loadDb()
  const t = findTask(tasks, id)
  if (!t.acceptance) {
    console.error(`${id} is a phase/stage row with no acceptance test — tick its leaves instead.`)
    process.exit(1)
  }
  t.status = 'done'
  t.tickedAt = nowIso()
  saveDb(tasks)
  cmdMirror()
  console.log(`Ticked ${id} done at ${t.tickedAt}. Mirror regenerated.`)
}

function cmdPart(id) {
  const tasks = loadDb()
  const t = findTask(tasks, id)
  t.status = 'partial'
  saveDb(tasks)
  cmdMirror()
  console.log(`Marked ${id} partial. Mirror regenerated.`)
}

function cmdNote(id, text) {
  const tasks = loadDb()
  const t = findTask(tasks, id)
  t.note = text
  saveDb(tasks)
  console.log(`Noted ${id}: ${text}`)
}

function cmdAdd(id, parent, title, acceptance, component) {
  const tasks = loadDb()
  if (tasks.some((t) => t.id === id)) {
    console.error(`${id} already exists.`)
    process.exit(1)
  }
  tasks.push({ id, parent, title, acceptance, component, status: 'open', note: '', tickedAt: null })
  saveDb(tasks)
  cmdMirror()
  console.log(`Added ${id} under ${parent || '(top level)'}.`)
}

function statusGlyph(status) {
  return status === 'done' ? '[x]' : status === 'partial' ? '[~]' : '[ ]'
}

function cmdTree() {
  const tasks = loadDb()
  const roots = tasks.filter((t) => !t.parent)
  const childrenOf = (id) => tasks.filter((t) => t.parent === id)
  const printNode = (t, depth) => {
    console.log('  '.repeat(depth) + `${statusGlyph(t.status)} ${t.id} ${t.title}`)
    for (const c of childrenOf(t.id)) printNode(c, depth + 1)
  }
  for (const r of roots.sort((a, b) => a.id.localeCompare(b.id))) printNode(r, 0)
}

function cmdComponents() {
  const tasks = loadDb()
  const leaves = tasks.filter((t) => t.acceptance)
  const byComponent = {}
  for (const t of leaves) {
    byComponent[t.component] ??= { total: 0, done: 0, partial: 0 }
    byComponent[t.component].total++
    if (t.status === 'done') byComponent[t.component].done++
    if (t.status === 'partial') byComponent[t.component].partial++
  }
  console.log(JSON.stringify(byComponent, null, 2))
  return byComponent
}

function cmdMirror() {
  const tasks = loadDb()
  const phases = tasks.filter((t) => !t.parent).sort((a, b) => a.id.localeCompare(b.id))
  const leaves = tasks.filter((t) => t.acceptance)
  const doneCount = leaves.filter((t) => t.status === 'done').length
  const lines = []
  lines.push('<!-- AUTO-GENERATED by phasedoc/plan.mjs mirror — do not hand-edit. Edit tasks.json or seed-tasks.mjs instead. -->')
  lines.push('# Buildplan Mirror — Aerotrack')
  lines.push('')
  lines.push(`Overall: ${doneCount}/${leaves.length} leaf tasks done (${Math.round((doneCount / leaves.length) * 100)}%)`)
  lines.push('')
  for (const phase of phases) {
    const children = tasks.filter((t) => t.parent === phase.id).sort((a, b) => a.id.localeCompare(b.id))
    const phaseDone = children.filter((c) => c.status === 'done').length
    lines.push(`## ${phase.id} ${phase.title} (${phaseDone}/${children.length})`)
    lines.push('')
    for (const c of children) {
      lines.push(`- ${statusGlyph(c.status)} **${c.id}** ${c.title} — _${c.component}_`)
      lines.push(`  - acceptance: ${c.acceptance}`)
      if (c.note) lines.push(`  - note: ${c.note}`)
      if (c.tickedAt) lines.push(`  - ticked: ${c.tickedAt}`)
    }
    lines.push('')
  }
  writeFileSync(MIRROR_PATH, lines.join('\n'))
}

const [, , cmd, ...rest] = process.argv

switch (cmd) {
  case 'init':
    await cmdInit()
    break
  case 'tick':
    cmdTick(rest[0])
    break
  case 'part':
    cmdPart(rest[0])
    break
  case 'note':
    cmdNote(rest[0], rest.slice(1).join(' '))
    break
  case 'add':
    cmdAdd(rest[0], rest[1], rest[2], rest[3], rest[4])
    break
  case 'tree':
    cmdTree()
    break
  case 'components':
    cmdComponents()
    break
  case 'mirror':
    cmdMirror()
    console.log('Mirror regenerated.')
    break
  default:
    console.log('Usage: node plan.mjs <init|tick|part|note|add|tree|components|mirror> [...args]')
    process.exit(1)
}
